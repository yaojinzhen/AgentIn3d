"""Query agent asset indexes without placing the full indexes in model context.

The JSON files generated by :mod:`inf_agent.tools.index_generator` are local data
stores. This module exposes bounded, deterministic views that are suitable for
an agent prompt or tool result.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any, Iterable

DEFAULT_API_LIMIT = 8
DEFAULT_DOCUMENT_LIMIT = 3
DEFAULT_API_MAX_CHARS = 12_000
DEFAULT_DOCUMENT_MAX_CHARS = 8_000
MIN_MAX_CHARS = 512
MAX_QUERY_CHARS = 500
API_INDEX_SCHEMA_VERSION = "1.0"
GENERIC_API_TERMS = frozenset(
    {"factory", "assetfactory", "createasset", "build", "new", "setup"}
)

DOCUMENT_DOMAINS = ("object", "pattern", "api", "material", "troubleshoot")
DEFAULT_OUTPUT_DIR = Path("inf_agent/modeling_docs/indexes")
DOCUMENT_DOMAIN_ROOTS = {
    "object": ("asset_examples/objects",),
    "pattern": ("modeling_patterns",),
    "api": ("api_reference/operation_routes",),
    "material": ("asset_examples/materials",),
    "troubleshoot": ("troubleshooting",),
}

_OBJECT_QUERY_SYNONYMS = {
    "apple": ("apple", "苹果", "果实"),
    "苹果": ("苹果", "apple", "果实"),
    "leaf": ("leaf", "叶", "叶片", "枝叶"),
    "broadleaf": ("broadleaf", "阔叶", "叶片", "枝叶"),
    "阔叶": ("阔叶", "broadleaf", "叶片", "枝叶"),
}

_SEPARATOR_RE = re.compile(r"[^0-9a-zA-Z_\u4e00-\u9fff]+")


class IndexQueryError(RuntimeError):
    """Raised when indexes cannot be loaded or a query is invalid."""


def resolve_index_dir(
    repo_root: Path | str,
    override: Path | str | None = None,
) -> Path:
    """Resolve indexes from exactly one repository or an explicit override."""

    root = Path(repo_root).resolve()
    if override is None:
        return root / DEFAULT_OUTPUT_DIR
    candidate = Path(override)
    return (
        candidate.resolve() if candidate.is_absolute() else (root / candidate).resolve()
    )


def _normalized(value: str) -> str:
    return " ".join(_SEPARATOR_RE.sub(" ", value.casefold()).split())


def _compact(value: str) -> str:
    return _normalized(value).replace(" ", "").replace("_", "")


def _query_terms(value: str) -> list[str]:
    return [term for term in _normalized(value).replace("_", " ").split() if term]


def _match_score(
    query: str,
    candidate: str,
    *,
    exact_score: int,
    contains_score: int,
    fuzzy_score: int,
) -> int:
    query_compact = _compact(query)
    candidate_compact = _compact(candidate)
    if not query_compact or not candidate_compact:
        return 0
    if query_compact == candidate_compact:
        return exact_score
    if _curated_phrase_occurs(query, candidate) or _curated_phrase_occurs(
        candidate, query
    ):
        return contains_score

    terms = _query_terms(query)
    if any(
        (_curated_phrase_occurs(candidate, term))
        or (_curated_phrase_occurs(term, candidate))
        for term in terms
    ):
        return contains_score - 5

    # Character-edit similarity is intentionally excluded.  It previously
    # routed ``apple`` to ``cable`` and ``revolve`` to ``volume``.  Curated
    # aliases and exact token/phrase matches are safer than plausible-looking
    # low-confidence results.
    return 0


def _curated_phrase_occurs(text: str, phrase: str) -> bool:
    """Match maintained aliases without allowing ASCII word substrings.

    Chinese aliases have no whitespace word boundary, so their normalized
    character sequence is matched directly.  English aliases are matched as
    complete token sequences; this prevents routes such as ``apple`` from
    matching ``pineapple`` or a generic API suffix from matching unrelated
    symbols.
    """

    normalized_text = _normalized(text).replace("_", " ")
    normalized_phrase = _normalized(phrase).replace("_", " ")
    if not normalized_text or not normalized_phrase:
        return False
    if re.search(r"[\u4e00-\u9fff]", normalized_phrase):
        return _compact(phrase) in _compact(text)
    phrase_tokens = normalized_phrase.split()
    text_tokens = normalized_text.split()
    width = len(phrase_tokens)
    return any(
        text_tokens[index : index + width] == phrase_tokens
        for index in range(len(text_tokens) - width + 1)
    )


def _best_field_matches(
    query: str,
    values: Iterable[tuple[str, str, int, int, int]],
) -> tuple[int, list[str]]:
    scored: list[tuple[int, str]] = []
    variants = _OBJECT_QUERY_SYNONYMS.get(_normalized(query), (query,))
    for variant in variants:
        for label, value, exact_score, contains_score, fuzzy_score in values:
            score = _match_score(
                variant,
                value,
                exact_score=exact_score,
                contains_score=contains_score,
                fuzzy_score=fuzzy_score,
            )
            if score:
                scored.append((score, f"{label}:{value}"))
    if not scored:
        return 0, []
    scored.sort(key=lambda item: (-item[0], item[1]))
    return scored[0][0], [label for _, label in scored[:5]]


def _parse_frontmatter(path: Path) -> dict[str, Any] | None:
    """Read the small JSON-compatible frontmatter used by routing cards."""

    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        return None
    end = text.find("\n---\n", 4)
    if end < 0:
        raise IndexQueryError(f"unterminated routing frontmatter: {path}")
    metadata: dict[str, Any] = {}
    for raw_line in text[4:end].splitlines():
        if not raw_line.strip() or raw_line.lstrip().startswith("#"):
            continue
        key, separator, raw_value = raw_line.partition(":")
        if not separator or not key.strip():
            raise IndexQueryError(
                f"invalid routing frontmatter line: {path}: {raw_line}"
            )
        value = raw_value.strip()
        if value.startswith("["):
            try:
                parsed = json.loads(value)
            except json.JSONDecodeError as error:
                raise IndexQueryError(
                    f"invalid routing list in {path}: {raw_line}"
                ) from error
            if not isinstance(parsed, list) or not all(
                isinstance(item, str) for item in parsed
            ):
                raise IndexQueryError(
                    f"routing list must contain strings: {path}: {key}"
                )
            metadata[key.strip()] = parsed
        else:
            metadata[key.strip()] = value.strip('"')
    body = text[end + 5 :]
    heading = next(
        (
            line.lstrip("# ").strip()
            for line in body.splitlines()
            if line.startswith("# ")
        ),
        path.stem.replace("_", " "),
    )
    metadata["heading"] = heading
    return metadata


def _document_paths(repo_root: Path, domain: str) -> list[Path]:
    if domain not in DOCUMENT_DOMAIN_ROOTS:
        raise IndexQueryError(f"unknown documentation domain: {domain}")
    doc_root = repo_root / "inf_agent" / "modeling_docs"
    return sorted(
        path
        for relative_root in DOCUMENT_DOMAIN_ROOTS[domain]
        for path in (doc_root / relative_root).glob("*.md")
        if path.is_file()
    )


def load_document_routes(repo_root: Path, domain: str) -> list[dict[str, Any]]:
    """Load routing-card metadata without placing document bodies in output."""

    doc_root = repo_root / "inf_agent" / "modeling_docs"
    routes: list[dict[str, Any]] = []
    for path in _document_paths(repo_root, domain):
        metadata = _parse_frontmatter(path)
        if metadata is None:
            continue
        if metadata.get("domain") != domain:
            raise IndexQueryError(
                f"routing card domain mismatch: {path}: {metadata.get('domain')!r}"
            )
        required = ("id", "intent", "aliases", "use_when", "avoid_when", "summary")
        missing = [key for key in required if not metadata.get(key)]
        if missing:
            raise IndexQueryError(f"routing card missing {', '.join(missing)}: {path}")
        metadata["document"] = path.relative_to(doc_root).as_posix()
        if domain == "api":
            documents = metadata.get("documents")
            if not isinstance(documents, list) or not 1 <= len(documents) <= 3:
                raise IndexQueryError(
                    f"API operation route must declare 1-3 documents: {path}"
                )
            for document in documents:
                target = (doc_root / document).resolve()
                try:
                    relative = target.relative_to(doc_root.resolve()).as_posix()
                except ValueError as error:
                    raise IndexQueryError(
                        f"API operation target escapes document root: {path}: {document}"
                    ) from error
                if (
                    not target.is_file()
                    or not relative.startswith(
                        (
                            "api_reference/function_api/",
                            "api_reference/material_api/",
                            "api_reference/node_api/",
                        )
                    )
                    or target.name == "README.md"
                ):
                    raise IndexQueryError(
                        f"invalid API leaf target: {path}: {document}"
                    )
        routes.append(metadata)
    return routes


def _phrase_tokens(value: str) -> set[str]:
    return set(_query_terms(value))


def _document_score(query: str, route: dict[str, Any]) -> tuple[int, str, str]:
    normalized_query = _normalized(query)
    compact_query = _compact(query)
    if not compact_query:
        return 0, "none", ""
    fields = [("id", str(route["id"])), *[("alias", item) for item in route["aliases"]]]
    fields.extend(("symbol", item) for item in route.get("source_symbols", []))
    fields.append(("intent", str(route["intent"])))
    for label, value in fields:
        if normalized_query == _normalized(value):
            return 100, "exact", f"exact {label} match: {value}"
    query_tokens = _phrase_tokens(query)
    # Longest maintained aliases win when several natural phrases occur.
    # This makes e.g. "wine glass" more specific than "glass".
    ordered_fields = sorted(
        fields,
        key=lambda item: (
            -len(_query_terms(item[1])),
            -len(_compact(item[1])),
            item[0],
        ),
    )
    for label, value in ordered_fields:
        value_tokens = _phrase_tokens(value)
        if _curated_phrase_occurs(query, value):
            specificity = min(5, max(0, len(value_tokens) - 1))
            return (
                93 + specificity,
                "token",
                f"curated {label} token match: {value}",
            )
    descriptive = " ".join(str(route.get(key, "")) for key in ("use_when", "summary"))
    descriptive_tokens = _phrase_tokens(descriptive)
    if query_tokens and query_tokens.issubset(descriptive_tokens):
        return 80, "intent", "all query tokens occur in the maintained intent metadata"
    return 0, "none", ""


def _readable_references(repo_root: Path, result: dict[str, Any]) -> dict[str, Any]:
    """Separate reader inputs from headings, source locations and external APIs."""
    from inf_agent.knowledge.resolver import read_knowledge
    from inf_agent.workspace.contracts import ContractError

    documents = []
    document_refs = []
    for value in result.get("documents", []):
        path, _, heading = value.partition("#")
        if path not in documents:
            documents.append(path)
        document_refs.append({"path": path, "heading": heading or None})
    result.update(
        document=documents[0] if documents else None,
        document_path=documents[0] if documents else None,
        document_heading=document_refs[0]["heading"] if document_refs else None,
        documents=documents,
        document_references=document_refs,
    )
    symbols = []
    references = []
    for value in result.get("source_symbols", []):
        module, separator, name = value.partition(":")
        reference = {"value": value}
        canonical = None
        if separator and not name.isdecimal():
            if module.endswith(".py"):
                module = module[:-3].replace("/", ".").replace("\\", ".")
                if module.endswith(".__init__"):
                    module = module[:-9]
            canonical = f"{module}:{name}"
            try:
                source = read_knowledge(repo_root, symbol=canonical)
            except (ContractError, SyntaxError):
                canonical = None
            else:
                reference.update(
                    kind="repository_symbol",
                    symbol=canonical,
                    source_path=Path(source["path"])
                    .relative_to(repo_root.resolve())
                    .as_posix(),
                    source_line=source["start_line"],
                )
                symbols.append(canonical)
        if canonical is None:
            path = repo_root / value
            if path.is_dir():
                reference["kind"] = "repository_directory"
            elif (repo_root / (value.replace(".", "/") + ".py")).is_file():
                reference["kind"] = "repository_module"
            elif ".py:" in value:
                source_path, _, line = value.partition(":")
                reference.update(kind="source_location", source_path=source_path)
                if line.isdecimal():
                    reference["source_line"] = int(line)
            elif (
                separator
                and repo_root.joinpath(*module.split(".")).with_suffix(".py").is_file()
            ):
                reference.update(
                    kind="source_location",
                    source_path=repo_root.joinpath(*module.split("."))
                    .with_suffix(".py")
                    .relative_to(repo_root)
                    .as_posix(),
                )
            else:
                reference["kind"] = "external_api"
        references.append(reference)
    result["source_symbols"] = list(dict.fromkeys(symbols))
    result["source_references"] = references
    return result


def query_document_routes(
    repo_root: Path,
    domain: str,
    query: str,
    *,
    limit: int = DEFAULT_DOCUMENT_LIMIT,
) -> list[dict[str, Any]]:
    """Return high-confidence, domain-isolated documentation routes."""

    query = query[:MAX_QUERY_CHARS]
    if not query.strip():
        raise IndexQueryError(f"{domain} query must not be empty")
    ranked: list[tuple[int, str, dict[str, Any]]] = []
    for route in load_document_routes(repo_root, domain):
        if domain == "api" and _api_identifier(query):
            names = [route["id"], *route["aliases"], *route.get("source_symbols", [])]
            if not any(_compact(query) == _compact(name) for name in names):
                continue
        score, match_type, why = _document_score(query, route)
        if score < 80:
            continue
        documents = list(route.get("documents", []))
        result = {
            "id": route["id"],
            "route_type": "api_operation" if domain == "api" else "document",
            "match_type": "operation_route" if domain == "api" else match_type,
            **({"route_match_type": match_type} if domain == "api" else {}),
            "confidence": round(score / 100, 2),
            "lexical_confidence": round(score / 100, 2),
            "semantic_applicability": "candidate",
            "why": why,
            "document": (
                documents[0] if documents else f"{route['document']}#{route['heading']}"
            ),
            "documents": documents or [f"{route['document']}#{route['heading']}"],
            "summary": route["summary"],
            "use_when": route["use_when"],
            "avoid_when": route["avoid_when"],
            "source_symbols": route.get("source_symbols", []),
            "related_patterns": route.get("related_patterns", []),
        }
        if documents:
            result["route_source"] = f"{route['document']}#{route['heading']}"
        ranked.append(
            (score, str(route["id"]), _readable_references(repo_root, result))
        )
    ranked.sort(key=lambda item: (-item[0], item[1]))
    return [item[2] for item in ranked[: _validated_limit(limit)]]


def documentation_query_result(
    repo_root: Path,
    domain: str,
    query: str,
    *,
    limit: int = DEFAULT_DOCUMENT_LIMIT,
    index_dir: Path | str | None = None,
) -> dict[str, Any]:
    limit = _validated_limit(limit)
    if domain == "api":
        api_index = load_api_index(
            resolve_index_dir(repo_root, index_dir) / "api_index.json"
        )
        symbols = query_api_symbols(
            api_index,
            query,
            documented_only=True,
            limit=limit,
        )
        interfaces = query_documented_interfaces(api_index, query, limit=limit)
        exact_symbols = [
            symbol for symbol in symbols if symbol["match_type"] == "exact_symbol"
        ]
        exact_interfaces = [
            interface
            for interface in interfaces
            if interface["match_type"] == "exact_documented_interface"
            and interface["name"] not in {item["qualname"] for item in exact_symbols}
        ]
        if exact_symbols or exact_interfaces:
            matches = [
                *(
                    _standardize_api_symbol(repo_root, symbol)
                    for symbol in exact_symbols
                ),
                *(
                    _standardize_documented_interface(repo_root, interface)
                    for interface in exact_interfaces
                ),
            ][:limit]
        else:
            aliases = [item for item in interfaces if item["match_type"] == "alias"]
            aliases += [item for item in symbols if item["match_type"] == "alias"]
            matches = [
                _standardize_documented_interface(repo_root, item)
                if item["kind"] == "documented_interface"
                else _standardize_api_symbol(repo_root, item)
                for item in aliases
            ][:limit]
            if not matches:
                matches = query_document_routes(repo_root, domain, query, limit=limit)
            if not matches:
                related = [
                    (
                        item["score"],
                        item["id"],
                        _standardize_api_symbol(repo_root, item),
                    )
                    for item in symbols
                ] + [
                    (
                        item["score"],
                        item["id"],
                        _standardize_documented_interface(repo_root, item),
                    )
                    for item in interfaces
                ]
                related.sort(key=lambda item: (-item[0], item[1]))
                matches = [item[2] for item in related[:limit]]
    else:
        matches = query_document_routes(repo_root, domain, query, limit=limit)
    return {
        "success": True,
        "query_type": domain,
        "query": query[:MAX_QUERY_CHARS],
        "returned_count": len(matches),
        "matches": matches,
        "next_queries": [] if matches else _next_queries(domain, query),
    }


def _standardize_api_symbol(repo_root: Path, symbol: dict[str, Any]) -> dict[str, Any]:
    documents = list(symbol.get("api_docs") or [])[:3]
    return _readable_references(
        repo_root,
        {
            "id": symbol["id"],
            "route_type": "source_symbol",
            "match_type": symbol["match_type"],
            "confidence": _api_confidence(symbol["match_type"]),
            "why": ", ".join(symbol.get("matched_on", [])),
            "document": (documents or [symbol.get("source", "")])[0],
            "documents": documents,
            "summary": symbol.get("summary")
            or symbol.get("signature")
            or symbol["name"],
            "use_when": f"检查候选接口 {symbol['qualname']}。",
            "avoid_when": "当前代码操作与该接口无关，或仍未确定建模机制。",
            "source_symbols": [symbol["id"]],
            "source_path": symbol.get(
                "source_path", symbol.get("source", "").partition(":")[0]
            ),
            "source_line": symbol.get("line_start"),
            "related_patterns": [],
        },
    )


def _standardize_documented_interface(
    repo_root: Path, interface: dict[str, Any]
) -> dict[str, Any]:
    documents = list(interface.get("documents") or [interface["document"]])[:3]
    return _readable_references(
        repo_root,
        {
            "id": interface["id"],
            "route_type": "documented_interface",
            "match_type": interface["match_type"],
            "confidence": _api_confidence(interface["match_type"]),
            "why": ", ".join(interface["matched_on"]),
            "document": documents[0],
            "documents": documents,
            "summary": f"接口 {interface['name']} 的固定版本调用事实。",
            "use_when": f"正在调用或适配接口 {interface['name']}。",
            "avoid_when": "当前代码操作与该接口无关，或仍未确定建模机制。",
            "source_symbols": [interface["name"]],
            "related_patterns": [],
        },
    )


def _next_queries(domain: str, query: str) -> list[str]:
    if domain == "object":
        return [
            f"query pattern --query '<dominant morphology of {query[:80]}>'",
            "query api --query '<exact symbol or modeling operation>'",
        ]
    if domain == "api":
        return ["use an exact symbol name", "query pattern for the modeling mechanism"]
    if domain == "material":
        return [
            "query a material family such as leaf, fruit skin, wood, metal, or glass"
        ]
    if domain == "troubleshoot":
        return ["query the error code or failure domain from preview summary"]
    return ["describe the dominant silhouette or geometric mechanism"]


def _api_identifier(query: str) -> bool:
    """A punctuated identifier is one unit, never a bag of shared words."""
    return bool(re.fullmatch(r"[A-Za-z_]\w*(?:[.:]\w+)*", query.strip())) and any(
        mark in query for mark in "_.:"
    )


def _api_confidence(match_type: str) -> float:
    # Lexical evidence strength, not a probability of modeling suitability.
    return {
        "exact_symbol": 1.0,
        "exact_documented_interface": 1.0,
        "alias": 0.95,
        "token_related": 0.5,
    }[match_type]


def _api_score(query: str, symbol: dict[str, Any]) -> tuple[int, list[str]]:
    query = query.strip()
    module = symbol.get("module", "")
    identities = {
        "id": symbol["id"],
        "name": symbol["name"],
        "module_symbol": f"{module}:{symbol['qualname'].removeprefix(module + '.')}",
        "qualname": symbol["qualname"],
        "qualified_name": f"{module}.{symbol['qualname']}",
    }
    for field, value in identities.items():
        if query.casefold() == value.casefold():
            return 1000, [f"exact_symbol:{field}:{value}"]
    if symbol.get("bl_idname", "").casefold() == query.casefold():
        return 900, [f"alias:bl_idname:{symbol['bl_idname']}"]
    if _api_identifier(query):
        return 0, []
    score, evidence = _best_field_matches(
        query,
        [
            ("name", symbol["name"], 150, 130, 0),
            ("qualname", symbol["qualname"], 150, 125, 0),
            ("module", module, 110, 90, 0),
            ("summary", symbol.get("summary", ""), 80, 60, 0),
        ],
    )
    return score, [f"token_related:{item}" for item in evidence]


def _compact_api_symbol(
    symbol: dict[str, Any],
    *,
    score: int,
    matched_on: list[str],
    include_details: bool,
) -> dict[str, Any]:
    source = symbol["source_path"]
    if line := symbol.get("line_start"):
        source += f":{line}"
    result = {
        "id": symbol["id"],
        "name": symbol["name"],
        "qualname": symbol["qualname"],
        "kind": symbol["kind"],
        "score": score,
        "matched_on": matched_on,
        "match_type": matched_on[0].split(":", 1)[0],
        "signature": symbol.get("signature"),
        "roles": symbol.get("roles", []),
        "source": source,
        "source_path": symbol["source_path"],
        "line_start": symbol.get("line_start"),
        "api_docs": symbol.get("api_docs", []),
    }
    if summary := symbol.get("summary"):
        result["summary"] = summary
    if bl_idname := symbol.get("bl_idname"):
        result["bl_idname"] = bl_idname
    if include_details:
        for key in (
            "module",
            "source_path",
            "line_start",
            "line_end",
            "declaration_lines",
            "parent_id",
            "bases",
            "methods",
            "decorators",
            "value",
            "values",
        ):
            if key in symbol:
                result[key] = symbol[key]
    return result


def query_api_symbols(
    api_index: dict[str, Any],
    query: str | None = None,
    *,
    symbol_id: str | None = None,
    roles: Iterable[str] = (),
    kinds: Iterable[str] = (),
    documented_only: bool = False,
    limit: int = DEFAULT_API_LIMIT,
    include_details: bool = False,
) -> list[dict[str, Any]]:
    """Return ranked, compact API symbols with optional filters."""

    query = query[:MAX_QUERY_CHARS] if query is not None else None
    symbol_id = symbol_id[:MAX_QUERY_CHARS] if symbol_id is not None else None
    if bool(query and query.strip()) == bool(symbol_id and symbol_id.strip()):
        raise IndexQueryError("provide exactly one of query or symbol_id")
    if symbol_id is None and _compact(query or "") in GENERIC_API_TERMS:
        return []

    role_filter = set(roles)
    kind_filter = set(kinds)
    ranked: list[tuple[int, str, dict[str, Any], list[str]]] = []
    for symbol in api_index.get("symbols", []):
        if role_filter and not role_filter.intersection(symbol.get("roles", [])):
            continue
        if kind_filter and symbol.get("kind") not in kind_filter:
            continue
        if documented_only and not symbol.get("api_docs"):
            continue

        if symbol_id is not None:
            if symbol["id"] != symbol_id:
                continue
            score, matched_on = 1_000, [f"exact_symbol:id:{symbol_id}"]
        else:
            score, matched_on = _api_score(query or "", symbol)
            if not score:
                continue
            if symbol.get("api_docs"):
                score += 5
        ranked.append((score, symbol["id"], symbol, matched_on))

    ranked.sort(key=lambda item: (-item[0], item[1]))
    if ranked and ranked[0][0] >= 900:
        top_score = ranked[0][0]
        ranked = [item for item in ranked if item[0] == top_score]
    return [
        _compact_api_symbol(
            symbol,
            score=score,
            matched_on=matched_on,
            include_details=include_details,
        )
        for score, _, symbol, matched_on in ranked[: _validated_limit(limit)]
    ]


def query_documented_interfaces(
    api_index: dict[str, Any],
    query: str,
    *,
    limit: int = DEFAULT_API_LIMIT,
) -> list[dict[str, Any]]:
    """Return exact or phrase matches for heading-owned documented interfaces."""

    query = query[:MAX_QUERY_CHARS]
    if not query.strip():
        raise IndexQueryError("API interface query must not be empty")
    ranked: list[tuple[int, str, dict[str, Any]]] = []
    for interface in api_index.get("documented_interfaces", []):
        name = interface["name"]
        if query.strip().casefold() == name.casefold():
            score, match_type, evidence = 1000, "exact_documented_interface", name
        elif alias := next(
            (
                alias
                for alias in interface.get("aliases", [])
                if _normalized(query).replace("_", " ")
                == _normalized(alias).replace("_", " ")
            ),
            None,
        ):
            score, match_type, evidence = 900, "alias", alias
        elif _api_identifier(query):
            continue
        else:
            score = _match_score(
                query, name, exact_score=150, contains_score=130, fuzzy_score=0
            )
            match_type, evidence = "token_related", name
        if not score:
            continue
        result = dict(interface)
        result.update(
            score=score, match_type=match_type, matched_on=[f"{match_type}:{evidence}"]
        )
        ranked.append((score, interface["id"], result))
    ranked.sort(key=lambda item: (-item[0], item[1]))
    if ranked and ranked[0][0] >= 900:
        top_score = ranked[0][0]
        ranked = [item for item in ranked if item[0] == top_score]
    return [item[2] for item in ranked[: _validated_limit(limit)]]


def _validated_limit(limit: int) -> int:
    if limit < 1:
        raise IndexQueryError("limit must be at least 1")
    return limit


def _minimal_match(record: dict[str, Any]) -> dict[str, Any]:
    result = {"id": record.get("id")}
    for key in ("name", "family_name", "kind", "source"):
        if value := record.get(key):
            result[key] = value
    result["fields_truncated"] = True
    return result


def render_bounded_result(
    *,
    query_type: str,
    query: str,
    records: list[dict[str, Any]],
    max_chars: int,
    requested_limit: int,
) -> str:
    """Serialize query results without exceeding the context character budget."""

    if max_chars < MIN_MAX_CHARS:
        raise IndexQueryError(f"max_chars must be at least {MIN_MAX_CHARS}")
    safe_query = query[:MAX_QUERY_CHARS]
    payload: dict[str, Any] = {
        "query_type": query_type,
        "query": safe_query,
        "requested_limit": requested_limit,
        "returned_count": 0,
        "truncated": False,
        "matches": [],
    }

    def serialize() -> str:
        return json.dumps(payload, ensure_ascii=False, indent=2) + "\n"

    for record in records:
        payload["matches"].append(record)
        payload["returned_count"] = len(payload["matches"])
        if len(serialize()) <= max_chars:
            continue
        payload["matches"].pop()
        payload["returned_count"] = len(payload["matches"])
        payload["truncated"] = True
        break

    if records and not payload["matches"]:
        payload["matches"] = [_minimal_match(records[0])]
        payload["returned_count"] = 1
        payload["truncated"] = True

    result = serialize()
    if len(result) > max_chars:
        payload["matches"] = []
        payload["returned_count"] = 0
        payload["truncated"] = True
        payload["error"] = "character budget too small for the first match"
        result = serialize()
    if len(result) > max_chars:
        raise IndexQueryError("max_chars is too small for query metadata")
    return result


def load_index(path: Path, expected_collection: str) -> dict[str, Any]:
    """Load and minimally validate one generated index."""

    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as error:
        raise IndexQueryError(f"missing index: {path}") from error
    except (OSError, json.JSONDecodeError) as error:
        raise IndexQueryError(f"cannot read index {path}: {error}") from error
    if not isinstance(value, dict) or not isinstance(
        value.get(expected_collection), list
    ):
        raise IndexQueryError(
            f"invalid index {path}: expected a {expected_collection!r} list"
        )
    return value


def load_api_index(path: Path) -> dict[str, Any]:
    """Load the current API schema including the documented-interface registry."""

    value = load_index(path, "symbols")
    if value.get("schema_version") != API_INDEX_SCHEMA_VERSION or not isinstance(
        value.get("documented_interfaces"), list
    ):
        raise IndexQueryError(
            f"stale API index {path}; run python -m inf_agent.tools.generate_indexes"
        )
    return value


def _default_repo_root() -> Path:
    return Path(__file__).resolve().parents[2]


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Query bounded views of the API index."
    )
    parser.add_argument(
        "--repo-root",
        type=Path,
        default=_default_repo_root(),
        help="Repository root. Defaults to the parent of the inf_agent package.",
    )
    parser.add_argument(
        "--index-dir",
        type=Path,
        default=None,
        help=f"Index directory. Defaults to {DEFAULT_OUTPUT_DIR}.",
    )
    subparsers = parser.add_subparsers(dest="command", required=True)

    api_parser = subparsers.add_parser("api", help="Query API symbols.")
    api_lookup = api_parser.add_mutually_exclusive_group(required=True)
    api_lookup.add_argument("--query", "-q")
    api_lookup.add_argument("--id", dest="symbol_id")
    api_parser.add_argument("--role", action="append", default=[])
    api_parser.add_argument("--kind", action="append", default=[])
    api_parser.add_argument("--documented-only", action="store_true")
    api_parser.add_argument("--limit", type=int, default=DEFAULT_API_LIMIT)
    api_parser.add_argument("--max-chars", type=int, default=DEFAULT_API_MAX_CHARS)
    api_parser.add_argument("--include-details", action="store_true")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", newline="\n")
    if hasattr(sys.stderr, "reconfigure"):
        sys.stderr.reconfigure(encoding="utf-8", newline="\n")
    try:
        args = parse_args(argv)
        repo_root = args.repo_root.resolve()
        index_dir = resolve_index_dir(repo_root, args.index_dir)
        index = load_api_index(index_dir / "api_index.json")
        records = query_api_symbols(
            index,
            args.query,
            symbol_id=args.symbol_id,
            roles=args.role,
            kinds=args.kind,
            documented_only=args.documented_only,
            limit=args.limit,
            include_details=args.include_details,
        )
        result = render_bounded_result(
            query_type="api",
            query=args.query or args.symbol_id,
            records=records,
            max_chars=args.max_chars,
            requested_limit=args.limit,
        )
    except IndexQueryError as error:
        print(f"index query error: {error}", file=sys.stderr)
        return 2

    print(result, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
